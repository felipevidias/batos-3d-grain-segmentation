#!/usr/bin/env python3
"""Phase 5f step 2: aggregate the v3.1 validation on dev + synthetic crops (f = 0.7 / 1.0 / 1.4 / 2.0).

fixflat and v3: the Phase 5e step-3 evaluations (C:\\BA_TOS_DATA\\runs\\v3_scale_test\\eval), unchanged.
v3.1: f = 1.4 / 2.0 from C:\\BA_TOS_DATA\\runs\\v31_dev\\eval; f = 0.7 / 1.0 = the v3 rows (flags identical by
construction, checked per crop in flag_identity.csv; EFRGP01_00_crop04 re-run bit-identical, identity_check.json).
Outputs: results/v31_dev/ crop_macro.csv, pooled.csv, per_crop.csv, seed_density.csv, tables.md.
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
V3 = Path(r"C:\BA_TOS_DATA\runs\v3_scale_test")
V31 = Path(r"C:\BA_TOS_DATA\runs\v31_dev")
OUT = REPO / "results" / "v31_dev"
METHODS = ["fixflat", "v3", "v3.1"]


def run_dir(method: str, f: float, crop: str) -> Path:
    return (V3 / "runs" / "v3" if method == "v3" else V31 / "runs") / f"x{f:g}" / crop


def seeds(method: str, f: float, crop: str) -> dict:
    base = run_dir(method, f, crop)
    if method == "v3.1" and f <= 1.0:
        base = run_dir("v3", f, crop)
    d = base / "e11" / "spatial" / "candidate_diagnostics_no_gt.csv"
    m = base / "e11" / "markers_tos_min" / "markers.csv"
    return {"min_candidates": int((pd.read_csv(d, usecols=["polarity"]).polarity == "min").sum()) if d.exists() else None,
            "tos_markers": int(len(pd.read_csv(m))) if m.exists() else None}


def main() -> int:
    ident = json.loads((V31 / "identity_check.json").read_text(encoding="utf-8"))
    if not all(v["identical"] for v in ident.values()):
        raise RuntimeError("identity check failed")
    flags = pd.read_csv(V31 / "flag_identity.csv")
    if not flags[flags.factor <= 1.0].flags_identical_to_v3.all():
        raise RuntimeError("v3.1 flags differ from v3 at s <= 1")
    base = pd.concat([pd.read_csv(p, dtype={"size_filter": str}) for p in sorted((V3 / "eval").glob("*.csv"))])
    new = pd.concat([pd.read_csv(p, dtype={"size_filter": str}) for p in sorted((V31 / "eval").glob("*.csv"))])
    low = base[(base.method == "v3") & (base.factor <= 1.0)].assign(method="v3.1")
    if sorted(new.factor.unique()) != [1.4, 2.0] or new.crop_id.nunique() != 24:
        raise RuntimeError(f"v3.1 synthetic evaluations incomplete: {new.crop_id.nunique()} crops")
    per = pd.concat([base, low, new], ignore_index=True)
    OUT.mkdir(parents=True, exist_ok=True)
    keys = ["factor", "method", "route", "size_filter", "mode"]
    macro, pooled = [], []
    for k, g in per.groupby(keys):
        b = dict(zip(keys, k)) | {"n_crops": len(g)}
        m = dict(b)
        for s in ("025", "050", "075"):
            f1 = g[f"f1_iou{s}"]
            m |= {f"f1_{s}_mean": f1.mean(), f"f1_{s}_sd": f1.std(ddof=1), f"f1_{s}_min": f1.min(),
                  f"f1_{s}_argmin": g.loc[f1.idxmin(), "crop_id"], f"n_below_090_{s}": int((f1 < 0.90).sum())}
        macro.append(m)
        tp, fp, fn = (int(g[f"{x}_iou050"].sum()) for x in ("tp", "fp", "fn"))
        pooled.append(b | {"valid_gt": int(g.valid_gt_count.sum()), "tp": tp, "fp": fp, "fn": fn,
                           "f1_050": 2 * tp / (2 * tp + fp + fn) if tp else 0.0})
    macro, pooled = pd.DataFrame(macro), pd.DataFrame(pooled)
    macro.to_csv(OUT / "crop_macro.csv", index=False)
    pooled.to_csv(OUT / "pooled.csv", index=False)

    prim = per[(per["mode"] == "markers_dominant") & (per.size_filter == "none") & (per.route == "BA-TOS_sel")]
    rows = []
    for r in prim.itertuples():
        if r.method == "fixflat":
            continue
        sd = seeds(r.method, r.factor, r.crop_id)
        gt_all = int(r.valid_gt_count + r.n_gt_excluded)
        rows.append({"crop_id": r.crop_id, "dev_crop_id": r.dev_crop_id, "factor": r.factor, "method": r.method,
                     **sd, "gt_valid": int(r.valid_gt_count), "gt_all": gt_all,
                     "candidates_per_grain": sd["min_candidates"] / gt_all if sd["min_candidates"] else None,
                     "markers_per_grain": sd["tos_markers"] / gt_all if sd["tos_markers"] else None,
                     "f1_050": r.f1_iou050, "precision": r.precision_iou050, "recall": r.recall_iou050,
                     "pred_total": r.n_pred_total})
    sd = pd.DataFrame(rows)
    sd.to_csv(OUT / "seed_density.csv", index=False)
    wide = prim.pivot_table(index=["dev_crop_id", "factor"], columns="method", values="f1_iou050").reset_index()
    wide.to_csv(OUT / "per_crop.csv", index=False)

    L = ["# v3.1 validation on dev + synthetic crops (generated by scripts/aggregate_v31_dev.py)", "",
         "v3.1 = v3 for f <= 1 (identical flags, checked per crop; EFRGP01_00_crop04 re-run bit-identical).", ""]
    for flt in ("none", "own"):
        L += [f"## Crop-macro F1@0.50, BA-TOS_sel, seed-ignore, size filter {flt}", "",
              "| f | n | fixflat | v3 | v3.1 | v3.1 min (crop) | # < 0.90 fixflat / v3 / v3.1 | pooled fixflat / v3 / v3.1 |",
              "|---|---|---|---|---|---|---|---|"]
        for f in sorted(per.factor.unique()):
            sel = lambda d: d[(d.factor == f) & (d.route == "BA-TOS_sel") & (d.size_filter == flt)  # noqa: E731
                              & (d["mode"] == "markers_dominant")].set_index("method")
            m, p = sel(macro), sel(pooled)
            L.append(f"| {f:g} | {int(m.loc['v3', 'n_crops'])} | " + " | ".join(
                f"{m.loc[k, 'f1_050_mean']:.3f} ± {m.loc[k, 'f1_050_sd']:.3f}" for k in METHODS)
                + f" | {m.loc['v3.1', 'f1_050_min']:.3f} ({m.loc['v3.1', 'f1_050_argmin']}) | "
                + " / ".join(str(int(m.loc[k, 'n_below_090_050'])) for k in METHODS) + " | "
                + " / ".join(f"{p.loc[k, 'f1_050']:.3f}" for k in METHODS) + " |")
        L.append("")
    L += ["## Seed density per GT grain (incl. face-touching; GT counts = diagnosis only), BA-TOS_sel", "",
          "| f | v3 MIN cand. | v3.1 MIN cand. | GT grains | v3 cand./grain | v3.1 cand./grain | v3 markers/grain "
          "| v3.1 markers/grain | v3 pred/grain | v3.1 pred/grain |", "|---|---|---|---|---|---|---|---|---|---|"]
    for f, g in sd.groupby("factor"):
        a, b = g[g.method == "v3"], g[g.method == "v3.1"]
        L.append(f"| {f:g} | {a.min_candidates.median():.0f} | {b.min_candidates.median():.0f} | {a.gt_all.median():.0f} "
                 f"| {a.candidates_per_grain.median():.2f} | {b.candidates_per_grain.median():.2f} "
                 f"| {a.markers_per_grain.median():.2f} | {b.markers_per_grain.median():.2f} "
                 f"| {(a.pred_total / a.gt_all).median():.2f} | {(b.pred_total / b.gt_all).median():.2f} |")
    L += ["", "## Per crop, f = 1.4 and 2.0 (F1@0.50 sel, no filter)", "",
          "| dev crop | f | fixflat | v3 | v3.1 | v3.1 markers/grain | v3.1 P / R |", "|---|---|---|---|---|---|---|"]
    for r in wide[wide.factor > 1].sort_values(["factor", "dev_crop_id"]).itertuples():
        s = sd[(sd.dev_crop_id == r.dev_crop_id) & (sd.factor == r.factor) & (sd.method == "v3.1")].iloc[0]
        L.append(f"| {r.dev_crop_id} | {r.factor:g} | {r.fixflat:.3f} | {r.v3:.3f} | {getattr(r, '_5'):.3f} "
                 f"| {s.markers_per_grain:.2f} | {s.precision:.2f} / {s.recall:.2f} |")
    (OUT / "tables.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
