#!/usr/bin/env python3
"""Phase 5i: aggregate v3c on dev + synthetic crops against v3 and v2-fixflat (Phase 5e step-3 evaluations).

Outputs: results/v3c_dev/{crop_macro,pooled,per_crop,seed_boundary,acceptance}.csv and tables.md.
Acceptance per docs/V3C_CANONICAL.md: f = 1.0 >= 0.976; f = 0.7 / 1.4 / 2.0 each >= 0.966 (crop-macro F1@0.50,
BA-TOS_sel, markers_dominant, no filter), 12 crops each.
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
V3 = Path(r"C:\BA_TOS_DATA\runs\v3_scale_test\eval")
V3C = Path(r"C:\BA_TOS_DATA\runs\v3c_dev\eval")
OUT = REPO / "results" / "v3c_dev"
THR = {1.0: 0.976, 0.7: 0.966, 1.4: 0.966, 2.0: 0.966}
METHODS = ["fixflat", "v3", "v3c"]


def main() -> int:
    rd = lambda ps: pd.concat([pd.read_csv(p, dtype={"size_filter": str}) for p in ps], ignore_index=True)  # noqa: E731
    per = pd.concat([rd(sorted(V3.glob("*.csv"))), rd(sorted(V3C.glob("*.csv")))], ignore_index=True)
    per = per[per.method.isin(METHODS)]
    OUT.mkdir(parents=True, exist_ok=True)
    keys = ["factor", "method", "route", "size_filter", "mode"]
    macro, pooled = [], []
    for k, g in per.groupby(keys):
        b = dict(zip(keys, k)) | {"n_crops": len(g)}
        m = dict(b)
        for s in ("050", "075"):
            f1 = g[f"f1_iou{s}"]
            m |= {f"f1_{s}_mean": f1.mean(), f"f1_{s}_sd": f1.std(ddof=1), f"f1_{s}_min": f1.min(),
                  f"f1_{s}_argmin": g.loc[f1.idxmin(), "crop_id"], f"n_below_090_{s}": int((f1 < 0.90).sum()),
                  f"miou_{s}_mean": g[f"mean_matched_iou{s}"].mean()}
        macro.append(m)
        row = dict(b)
        for s in ("050", "075"):
            tp, fp, fn = (int(g[f"{x}_iou{s}"].sum()) for x in ("tp", "fp", "fn"))
            row |= {f"tp_{s}": tp, f"fp_{s}": fp, f"fn_{s}": fn, f"f1_{s}": 2 * tp / (2 * tp + fp + fn) if tp else 0.0}
        pooled.append(row | {"valid_gt": int(g.valid_gt_count.sum())})
    macro, pooled = pd.DataFrame(macro), pd.DataFrame(pooled)
    macro.to_csv(OUT / "crop_macro.csv", index=False)
    pooled.to_csv(OUT / "pooled.csv", index=False)
    prim = per[(per["mode"] == "markers_dominant") & (per.route == "BA-TOS_sel")]
    wide = prim[prim.size_filter == "none"].pivot_table(index=["dev_crop_id", "factor"], columns="method",
                                                        values="f1_iou050").reset_index()
    wide.to_csv(OUT / "per_crop.csv", index=False)
    info = pd.DataFrame([json.loads(p.read_text(encoding="utf-8")) for p in sorted(V3C.glob("*.json"))])
    info.to_csv(OUT / "seed_boundary.csv", index=False)

    sel = lambda m, f, flt="none": macro[(macro.factor == f) & (macro.method == m) & (macro.route == "BA-TOS_sel")  # noqa: E731
                                         & (macro.size_filter == flt) & (macro["mode"] == "markers_dominant")]
    acc = []
    for f, thr in sorted(THR.items()):
        q = sel("v3c", f)
        n = int(q.n_crops.iloc[0]) if len(q) else 0
        v = float(q.f1_050_mean.iloc[0]) if len(q) else None
        acc.append({"factor": f, "n_crops": n, "f1_050": v, "threshold": thr,
                    "pass": (v >= thr) if (n == 12 and v is not None) else None})
    acc = pd.DataFrame(acc)
    acc.to_csv(OUT / "acceptance.csv", index=False)

    L = ["# v3c (canonical-scale normalization) on dev + synthetic crops (generated by scripts/aggregate_v3c_dev.py)", "",
         "Primary: crop-macro F1@0.50, BA-TOS_sel, seed-ignore (markers_dominant), no size filter.", "",
         "## Acceptance (docs/V3C_CANONICAL.md)", "", "| f | n | v3c F1@0.50 | threshold | pass |", "|---|---|---|---|---|"]
    L += [f"| {r.factor:g} | {r.n_crops} | {'' if pd.isna(r.f1_050) else f'{r.f1_050:.3f}'} | {r.threshold:.3f} | {r._5} |"
          for r in acc.itertuples()]
    for flt in ("none", "own"):
        for s in ("050", "075"):
            L += ["", f"## Crop-macro F1@0.{s[1:]}, filter {flt} (mean ± SD, min, # < 0.90; pooled; mean matched IoU)", "",
                  "| f | " + " | ".join(METHODS) + " |", "|---|" + "---|" * len(METHODS)]
            for f in sorted(per.factor.unique()):
                cells = []
                for m in METHODS:
                    q = sel(m, f, flt)
                    p = pooled[(pooled.factor == f) & (pooled.method == m) & (pooled.route == "BA-TOS_sel")
                               & (pooled.size_filter == flt) & (pooled["mode"] == "markers_dominant")]
                    cells.append("—" if q.empty else
                                 f"{q[f'f1_{s}_mean'].iloc[0]:.3f} ± {q[f'f1_{s}_sd'].iloc[0]:.3f}, min "
                                 f"{q[f'f1_{s}_min'].iloc[0]:.3f}, {int(q[f'n_below_090_{s}'].iloc[0])}; pooled "
                                 f"{p[f'f1_{s}'].iloc[0]:.3f}; mIoU {q[f'miou_{s}_mean'].iloc[0]:.3f} (n {int(q.n_crops.iloc[0])})")
                L.append(f"| {f:g} | " + " | ".join(cells) + " |")
    if len(info):
        L += ["", "## v3c seeds, canonical scale and boundary cost vs v3 (medians over crops; GT = diagnosis only)", "",
              "| f | n | r_granulo | canonical shape | gate fired | markers / grain (all GT) | markers / valid grain | "
              "valid seeded | valid split | markers in bg | mIoU v3c / v3 (common) | vol. err. v3c / v3 | |vol. err.| v3c / v3 |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for f, g in info.groupby("factor"):
            cs = g.canonical_shape.astype(str).value_counts().index[0]
            L.append(f"| {f:g} | {len(g)} | {g.r_granulo.median():g} | {cs} | {int(g.gate.fillna(False).astype(bool).sum())} | "
                     f"{g.seed_markers_per_grain_all.median():.2f} | {g.seed_markers_per_valid_grain.median():.2f} | "
                     f"{(g.seed_valid_seeded / g.seed_gt_valid).median():.3f} | {(g.seed_valid_split / g.seed_gt_valid).median():.3f} | "
                     f"{g.seed_markers_background.median():.0f} | {g.bnd_v3c_miou_common.median():.3f} / "
                     f"{g.bnd_v3_miou_common.median():.3f} | {g.bnd_v3c_volerr_median.median():+.3f} / "
                     f"{g.bnd_v3_volerr_median.median():+.3f} | {g.bnd_v3c_abs_volerr_median.median():.3f} / "
                     f"{g.bnd_v3_abs_volerr_median.median():.3f} |")
    L += ["", "## Per crop F1@0.50 (sel, no filter)", "", "| dev crop | f | " + " | ".join(METHODS) + " |",
          "|---|---|" + "---|" * len(METHODS)]
    for r in wide.sort_values(["factor", "dev_crop_id"]).itertuples(index=False):
        v = dict(zip(wide.columns, r))
        L.append(f"| {v['dev_crop_id']} | {v['factor']:g} | " + " | ".join(
            "—" if pd.isna(v.get(m)) else f"{v[m]:.3f}" for m in METHODS) + " |")
    (OUT / "tables.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L[:12]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
