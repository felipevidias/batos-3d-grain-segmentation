"""Generate the v3 patched copies of the three frozen scripts whose constants are hard-coded (not CLI flags).

The frozen files are read-only inputs; each copy differs from its source ONLY by the asserted replacements below,
which expose the hard-coded constant as a CLI flag whose default is the frozen value (so a copy called without the new
flags is behaviourally identical to the frozen script). Output: src/batos_v3/patched/*.py + patched_manifest.json
(source and copy SHA-256). Re-run after any change; never edit the copies by hand.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from batos_v2.frozen import SCRIPTS

OUT = Path(__file__).resolve().parent / "patched"

MASK_FN_OLD = "    min_component: int = 500,\n) -> tuple[np.ndarray, float]:"
MASK_FN_NEW = "    min_component: int = 500,\n    closing_iterations: int = 1,\n) -> tuple[np.ndarray, float]:"
ARGS_MASK = ('    return parser.parse_args()',
             '    # batos_v3 patch: hard-coded mask constants exposed (defaults = frozen values)\n'
             '    parser.add_argument("--v3-min-component", type=int, default=500)\n'
             '    parser.add_argument("--v3-closing-iterations", type=int, default=1)\n'
             '    return parser.parse_args()')
CALL_MASK = ("clean_bright_otsu_mask(image_norm)",
             "clean_bright_otsu_mask(image_norm, args.v3_min_component, args.v3_closing_iterations)")

PATCHES = {
    "e11_watershed": ("e11_run_fixed_mask_watershed_v3.py", [
        (MASK_FN_OLD, MASK_FN_NEW), ("        iterations=1,", "        iterations=int(closing_iterations),"),
        ARGS_MASK, CALL_MASK]),
    "e11_controls": ("e11_build_control_markers_v3.py", [
        (MASK_FN_OLD, MASK_FN_NEW), ("        iterations=1,", "        iterations=int(closing_iterations),"),
        ARGS_MASK, CALL_MASK]),
    "e23c_route": ("e23c_build_selective_marker_route_v3.py", [
        ('    return parser.parse_args()',
         '    # batos_v3 patch: gate limits exposed (defaults = frozen values)\n'
         '    parser.add_argument("--v3-median-limit", type=float, default=MEDIAN_LIMIT)\n'
         '    parser.add_argument("--v3-q75-limit", type=float, default=Q75_LIMIT)\n'
         '    return parser.parse_args()'),
        ("def main() -> int:\n    args = parse_args()",
         "def main() -> int:\n    global MEDIAN_LIMIT, Q75_LIMIT\n    args = parse_args()\n"
         "    MEDIAN_LIMIT, Q75_LIMIT = float(args.v3_median_limit), float(args.v3_q75_limit)")]),
}


def sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def main() -> int:
    OUT.mkdir(exist_ok=True)
    (OUT / "__init__.py").write_text('"""Generated by batos_v3.make_patched; do not edit."""\n', encoding="utf-8")
    manifest = {}
    for key, (name, reps) in PATCHES.items():
        src = Path(SCRIPTS[key])
        text = src.read_text(encoding="utf-8")
        new = text
        for old, rep in reps:
            if new.count(old) != 1:
                raise RuntimeError(f"{src.name}: expected exactly one occurrence of {old!r}, found {new.count(old)}")
            new = new.replace(old, rep)
        header = f"# GENERATED by src/batos_v3/make_patched.py from {src} (sha256 {sha(text)}); do not edit.\n"
        (OUT / name).write_text(header + new, encoding="utf-8")
        manifest[key] = {"source": str(src), "source_sha256": sha(text), "copy": name,
                         "copy_sha256": sha(header + new), "replacements": [[o, r] for o, r in reps]}
    (OUT / "patched_manifest.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")
    print(json.dumps({k: v["copy"] for k, v in manifest.items()}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
